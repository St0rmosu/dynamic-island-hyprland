#!/usr/bin/env python3
"""
apply_hyprland_binds.py
Updates ~/.config/hypr/moduli/binds.lua and ~/.config/dynamic-island/hyprland-shortcuts.conf
with custom shortcuts defined in Dynamic Island, then reloads Hyprland.
"""

import sys
import os
import json
import re
import subprocess

HOME = os.path.expanduser("~")
BINDS_LUA = os.path.join(HOME, ".config/hypr/moduli/binds.lua")
SHORTCUTS_CONF_DYNAMIC = os.path.join(HOME, ".config/dynamic-island/hyprland-shortcuts.conf")
# LEGACY_SHORTCUTS_CONF = os.path.join(HOME, ".config/dynamic-island/hyprland-shortcuts.conf")
CONFIG_JSON = os.path.join(HOME, ".config/dynamic-island/config.json")

# Map of action to human-readable names and defaults
ACTION_MAP = {
    "overview": "overview",
    "power": "power",
    "notifications": "notifications",
    "master-or-wallpaper": "master-or-wallpaper",
    "apps": "apps",
    "files": "files",
    "clipboard": "clipboard"
}

def format_lua_bind(keys, action):
    has_super = "SUPER" in keys
    other_keys = [k for k in keys if k != "SUPER"]
    mapped_other = ["space" if k == "Spazio" else k for k in other_keys]
    
    if has_super:
        if mapped_other:
            key_expr = f'mainMod .. " + {" + ".join(mapped_other)}"'
        else:
            key_expr = 'mainMod'
    else:
        mapped_all = ["space" if k == "Spazio" else k for k in keys]
        key_expr = f'"{ " + ".join(mapped_all) }"'
        
    return f'hl.bind({key_expr}, hl.dsp.exec_cmd("$HOME/.scripts/shell-dispatcher.sh {action}"))'

def format_conf_bind(keys, action):
    # Format for hyprland.conf style: bind = SUPER ALT, space, exec, ...
    mods = [k for k in keys if k in ("SUPER", "CTRL", "ALT", "SHIFT")]
    non_mods = [k for k in keys if k not in ("SUPER", "CTRL", "ALT", "SHIFT")]
    
    mod_str = " ".join(mods)
    key_str = non_mods[0] if non_mods else ""
    if key_str == "Spazio":
        key_str = "space"
    elif key_str == "Tab":
        key_str = "TAB"
        
    return f'bind = {mod_str}, {key_str}, exec, $HOME/.scripts/shell-dispatcher.sh {action}'

def main():
    shortcuts = None
    
    # Try reading from CLI argument first
    if len(sys.argv) > 1 and sys.argv[1].strip():
        try:
            shortcuts = json.loads(sys.argv[1])
        except Exception as e:
            pass
            
    # Fallback: read from config.json
    if not shortcuts and os.path.exists(CONFIG_JSON):
        try:
            with open(CONFIG_JSON, "r") as f:
                cfg = json.load(f)
                shortcuts = cfg.get("customShortcuts", [])
        except Exception:
            pass
            
    if not shortcuts or not isinstance(shortcuts, list):
        print(json.dumps({"status": "error", "message": "No valid shortcuts provided"}))
        return 1

    # 1. Update ~/.config/hypr/moduli/binds.lua
    updated_lua_count = 0
    if os.path.exists(BINDS_LUA):
        try:
            with open(BINDS_LUA, "r") as f:
                lua_content = f.read()

            for item in shortcuts:
                act = item.get("action")
                keys = item.get("keys", [])
                if not act or not keys:
                    continue

                new_line = format_lua_bind(keys, act)
                
                # Regex matches hl.bind(..., hl.dsp.exec_cmd("$HOME/.scripts/shell-dispatcher.sh <act>"))
                pattern = re.compile(
                    r'hl\.bind\([^,]+,\s*hl\.dsp\.exec_cmd\([\'"]\$HOME/\.scripts/shell-dispatcher\.sh\s+' + re.escape(act) + r'[\'"]\)\)',
                    re.MULTILINE
                )
                
                if pattern.search(lua_content):
                    lua_content, count = pattern.subn(new_line, lua_content, count=1)
                    if count > 0:
                        updated_lua_count += 1

            with open(BINDS_LUA, "w") as f:
                f.write(lua_content)
        except Exception as e:
            print(json.dumps({"status": "error", "message": f"Failed updating binds.lua: {e}"}))
            return 1

    # 2. Update ~/.config/dynamic-island/hyprland-shortcuts.conf
    updated_conf_count = 0
    try:
        conf_lines = []
        if os.path.exists(SHORTCUTS_CONF_DYNAMIC):
            with open(SHORTCUTS_CONF_DYNAMIC, "r") as f:
                conf_lines = f.readlines()
        else:
            os.makedirs(os.path.dirname(SHORTCUTS_CONF_DYNAMIC), exist_ok=True)
            conf_lines = [
                "# Generated by Dynamic Island.\n",
                "# These binds call shell-dispatcher or Quickshell IPC.\n"
            ]

        # Action to pattern matcher in hyprland-shortcuts.conf
        action_matchers = {
            "overview": lambda line: "overview toggle" in line or "shell-dispatcher.sh overview" in line,
            "power": lambda line: "togglePowerMenu" in line or "shell-dispatcher.sh power" in line,
            "notifications": lambda line: "toggleNotificationCenter" in line or "shell-dispatcher.sh notifications" in line,
            "master-or-wallpaper": lambda line: "toggleWallpaperPicker" in line or "shell-dispatcher.sh master-or-wallpaper" in line,
            "apps": lambda line: "toggleApplicationLauncher" in line or "shell-dispatcher.sh apps" in line,
            "files": lambda line: "toggleFileShelf" in line or "shell-dispatcher.sh files" in line,
            "clipboard": lambda line: "toggleClipboard" in line or "shell-dispatcher.sh clipboard" in line
        }

        # Format map for shortcuts
        formatted_map = {}
        for item in shortcuts:
            act = item.get("action")
            keys = item.get("keys", [])
            if act and keys:
                formatted_map[act] = format_conf_bind(keys, act)

        new_conf_lines = []
        replaced_actions = set()

        for line in conf_lines:
            replaced = False
            for act, bind_str in formatted_map.items():
                matcher = action_matchers.get(act, lambda l, a=act: f"shell-dispatcher.sh {a}" in l)
                if matcher(line):
                    new_conf_lines.append(bind_str + "\n")
                    replaced_actions.add(act)
                    replaced = True
                    updated_conf_count += 1
                    break
            if not replaced:
                new_conf_lines.append(line)

        # Append any actions not found in existing lines
        for act, bind_str in formatted_map.items():
            if act not in replaced_actions:
                new_conf_lines.append(bind_str + "\n")
                updated_conf_count += 1

        # Ensure layerrule for blur is present
        has_layer_blur = any("layerrule = blur, dynamic-island" in l for l in new_conf_lines)
        if not has_layer_blur:
            new_conf_lines.insert(0, "layerrule = blur, dynamic-island\nlayerrule = ignorealpha 0.15, dynamic-island\n")

        with open(SHORTCUTS_CONF_DYNAMIC, "w") as f:
            f.writelines(new_conf_lines)
    except Exception as e:
        print(f"Warning: could not update {SHORTCUTS_CONF_DYNAMIC}: {e}", file=sys.stderr)

    # 3. Reload Hyprland
    try:
        subprocess.run(["hyprctl", "reload"], check=False, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    except Exception:
        pass

    print(json.dumps({
        "status": "ok",
        "updated_binds": max(updated_lua_count, updated_conf_count),
        "message": f"Applicate {max(updated_lua_count, updated_conf_count)} scorciatoie a Hyprland!"
    }))
    return 0

if __name__ == "__main__":
    sys.exit(main())
